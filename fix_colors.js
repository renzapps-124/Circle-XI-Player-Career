const regex = /COUNTRIES:\s*\[([\s\S]*?)\]/s;
const match = content.match(regex);
if (match) {
    let countriesStr = match[1];
    let countries = [];
    // Carefully parse each line as JSON
    const lines = countriesStr.split('\n');
    const newLines = lines.map(line => {
        if (!line.trim()) return line;
        let c;
        try {
            c = JSON.parse(line.trim().replace(/,$/, ''));
        } catch (e) {
            return line;
        }
        
        let cols = authenticColors[c.name] || ["#ffffff", "#000000"];
        // if currently random or default, set it
        c.elementPalette = cols;
        return '      ' + JSON.stringify(c) + ',';
    });
    
    content = content.replace(regex, 'COUNTRIES: [\n' + newLines.join('\n') + '\n    ]');
}

